#  Phase 4 Test 4.1: Self-Hosting Lexer Written in Compound Hinglish!

type Token = object
  kind: string
  val: string

proc tokenizeCompound(src: string): seq[Token] {.discardable.} =
  var tokens = newSeq[Token]()
  var i = 0
  var n = src.len

  while i < n:
    var ch = src[i]
    if ch == ' ' or ch == '\t' or ch == '\n':
      i += 1
      continue

    if ch == '+' or ch == '-' or ch == '*' or ch == '=':
      var opStr = "" & ch
      tokens.add(Token(kind: "OPERATOR", val: opStr))
      i += 1
      continue

    if ch >= '0' and ch <= '9':
      var numStr = ""
      while i < n and src[i] >= '0' and src[i] <= '9':
        numStr.add(src[i])
        i += 1
      tokens.add(Token(kind: "NUMBER", val: numStr))
      continue

    if (ch >= 'a' and ch <= 'z') or (ch >= 'A' and ch <= 'Z') or ch == '_':
      var identStr = ""
      while i < n and ((src[i] >= 'a' and src[i] <= 'z') or (src[i] >= 'A' and src[i] <= 'Z') or src[i] == '_' or (src[i] >= '0' and src[i] <= '9')):
        identStr.add(src[i])
        i += 1
      tokens.add(Token(kind: "IDENTIFIER", val: identStr))
      continue

    i += 1

  return tokens

var testCode = "rakho ginti = 100 + 200"
echo "Input Source Code:", testCode

var resultTokens = tokenizeCompound(testCode)

echo "=== Tokens Generated by Compound Self-Hosted Lexer ==="
for tok in resultTokens:
  echo "Token Kind:", tok.kind, "-> Value:", tok.val
